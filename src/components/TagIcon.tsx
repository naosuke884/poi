export function TagIconSvg({ icon, size }: { icon: TagIcon | undefined; size: number }) {
  const paths = (icon && PATHS[icon]) ?? PATHS.other;
  return (
    <Svg size={size}>
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </Svg>
  );
}
