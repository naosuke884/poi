import { MEMO_TTL_CHOICES, MEMO_TTL_DAYS } from "@shared/constants";
import { SUB_PAGES } from "@shared/site";
import { createFileRoute, Link } from "@tanstack/react-router";
import { DocPage } from "./-components/DocPage";

// 使い方 (ログイン不要)。検索の入口にもなるよう、できることを画面の言葉で説明する (issue #152)
export const Route = createFileRoute("/(docs)/guide")({
  component: Guide,
});

// 選べる保存期間の幅 (設定の選択肢と食い違わないよう定数から作る)
const TTL_MIN = MEMO_TTL_CHOICES[0];
const TTL_MAX = MEMO_TTL_CHOICES[MEMO_TTL_CHOICES.length - 1];

function Guide() {
  return (
    <DocPage title={SUB_PAGES["/guide"].name}>
      <p>
        poi は、書いたメモが {MEMO_TTL_DAYS}{" "}
        日で自動で消えるメモ帳です。消えるメモなので、片付けや整理を気にせず、思いついたことをそのまま書いておけます。このページでは、書き方とメモが消えるしくみ、便利な機能を説明します。
      </p>

      <h2>はじめる</h2>
      <p>
        トップページから Google アカウントでログインすると、すぐに自分の板 (メモを書く場所)
        が開きます。アプリのインストールや、名前・パスワードの登録はいりません。
      </p>

      <h2>メモを書く</h2>
      <p>板は 1 枚の長いメモ帳で、「セクション」という単位に分かれています。</p>
      <ul>
        <li>「セクションを追加」を押すと新しいセクションができ、そのまま書き始められます。</li>
        <li>書いている途中で空行を 2 つ続けると、そこから次のセクションになります。</li>
        <li>
          書いた内容は自動で保存されます。保存できたかどうかは、ヘッダーのアイコンで分かります。
        </li>
        <li>
          書いたセクションは押すと (キーボードでは Enter で) 書き直せます。書き終わったら Esc
          キーか、セクションの外を押すと表示に戻ります。
        </li>
      </ul>

      <h2>Markdown で書く</h2>
      <p>
        メモは Markdown
        で書けます。書いている間は記号のまま、書き終わると見出しや箇条書きとして表示されます。
      </p>
      <ul>
        <li>
          <code># 見出し</code> (<code>##</code> で小さい見出し)
        </li>
        <li>
          <code>- 箇条書き</code>、<code>1. 番号付きの箇条書き</code> (Tab キーで字下げ)
        </li>
        <li>
          <code>- [ ] やること</code> (チェックボックス)
        </li>
        <li>
          <code>**太字**</code>、<code>`コード`</code>、<code>&gt; 引用</code>、リンク
        </li>
      </ul>

      <h2>メモが消えるしくみ</h2>
      <ul>
        <li>
          メモはセクションごとに、最初に書いてから保存期間 (初期設定では {MEMO_TTL_DAYS} 日)
          がたつと自動で消えます。あとから書き足しても、消える日は変わりません。
        </li>
        <li>
          セクションの上の線は、消えるまでの残りの日数を表すバーです。「あと N
          日」が減るにつれて線が短くなり、残り 1 日になるとオレンジ色になります。
        </li>
        <li>
          消えたメモは元に戻せません。残しておきたい内容は、消える前にコピーして別の場所に保存してください。新しいセクションに書き直せば、そこからまた保存期間のあいだ残ります。
        </li>
      </ul>

      <h2>保存期間を変える</h2>
      <p>
        右上のユーザーメニューの「保存期間の設定」で、メモが消えるまでの日数を {TTL_MIN}〜{TTL_MAX}{" "}
        日から選べます。変えると、今あるセクションも書いた日から数え直されます。短くしたときは、新しい期間をすでに過ぎているセクションがすぐに消えるので注意してください。
      </p>

      <h2>見出しごとにまとめて読む</h2>
      <p>
        ヘッダーの切り替えで、書いた順に並ぶ「タイムライン」と、見出しごとに集めた「まとめ」を切り替えられます。まとめでは、同じ見出しを付けたセクションが、書いた日付をまたいで一か所に集まります。たとえば毎日「#
        作業ログ」の見出しで書いておくと、作業の記録を続けて読めます。
      </p>

      <h2>コピー・画像・削除</h2>
      <p>セクションの上の線の右端にあるボタンで、そのセクションを操作できます。</p>
      <ul>
        <li>コピー: 本文をテキストとしてコピーします。</li>
        <li>スクショ: 表示しているとおりの画像にします。チャットや SNS にそのまま貼れます。</li>
        <li>削除: セクションを消します。数秒のあいだは「元に戻す」で取り消せます。</li>
      </ul>

      <h2>スマホで使う</h2>
      <p>
        スマホのブラウザでもそのまま使えます。ユーザーメニューの「ホーム画面に追加」から、アプリのようにホーム画面に置いて全画面で開けます。電波がないときも、前回開いたときの内容は読めます。
      </p>
      <p>同じ Google アカウントでログインすれば、パソコンとスマホで同じ板を使えます。</p>

      <h2>アカウントを削除する</h2>
      <p>
        ユーザーメニューの「アカウント削除」で、アカウントと書いたメモをすべて削除できます。詳しくは
        <Link to="/terms">利用規約</Link>と<Link to="/privacy">プライバシーポリシー</Link>
        をご覧ください。
      </p>
    </DocPage>
  );
}
