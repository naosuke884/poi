import {
  BOARD_MAX_LENGTH,
  BOARD_MAX_SECTIONS,
  MEMO_TTL_CHOICES,
  MEMO_TTL_DAYS,
} from "@shared/constants";
import { SUB_PAGES } from "@shared/site";
import { createFileRoute, Link } from "@tanstack/react-router";
import { DocPage } from "./-components/DocPage";

// よくある質問 (ログイン不要)。質問の形の検索や AI 検索の回答に引用されやすいよう、
// 質問を見出しにして答えを本文に書く。答えは折りたたまない (読み込んだだけで本文が読めるように。issue #151)
export const Route = createFileRoute("/(docs)/faq")({
  component: Faq,
});

// 選べる保存期間の幅 (設定の選択肢と食い違わないよう定数から作る)
const TTL_MIN = MEMO_TTL_CHOICES[0];
const TTL_MAX = MEMO_TTL_CHOICES[MEMO_TTL_CHOICES.length - 1];

function Faq() {
  return (
    <DocPage title={SUB_PAGES["/faq"].name}>
      <p>
        poi (書いたメモが {MEMO_TTL_DAYS} 日で消えるメモ帳) についてよくある質問です。画面の操作は
        <Link to="/guide">使い方</Link>で詳しく説明しています。
      </p>

      <h2>消えたメモは元に戻せますか？</h2>
      <p>
        戻せません。保存期間を過ぎて消えたメモは、運営者に頼んでも復元できません。残しておきたい内容は、消える前にコピーして別の場所に保存してください。自分で削除したセクションは、削除した直後の数秒のあいだだけ「元に戻す」で取り消せます。
      </p>

      <h2>メモはいつ消えますか？</h2>
      <p>
        セクションごとに、最初に書いてから保存期間 (初期設定では {MEMO_TTL_DAYS} 日)
        がたつと自動で消えます。各セクションの上の線に「あと N 日」と残りの日数が出て、残り 1
        日になるとオレンジ色になるので、消える前に気づけます。
      </p>

      <h2>書き足したり直したりすると、消える日は延びますか？</h2>
      <p>
        延びません。消える日は、そのセクションを最初に書いた日から数えます。続きを長く残したいときは、新しいセクションに書いてください。
      </p>

      <h2>保存期間は変えられますか？</h2>
      <p>
        変えられます。ユーザーメニューの「保存期間の設定」で {TTL_MIN}〜{TTL_MAX}{" "}
        日から選べます。変えると、今あるセクションも書いた日から数え直されます。短くしたときは、新しい期間をすでに過ぎているセクションがすぐに消えます。
      </p>

      <h2>無料ですか？</h2>
      <p>無料で使えます。有料のプランはありません。</p>

      <h2>スマホで使えますか？</h2>
      <p>
        使えます。スマホのブラウザでそのまま開けるほか、ユーザーメニューの「ホーム画面に追加」から、アプリのようにホーム画面に置いて全画面で開けます。App
        Store や Google Play からインストールするアプリはありません。
      </p>

      <h2>電波がないときも使えますか？</h2>
      <p>
        ホーム画面に追加しているか、一度開いたことがあれば、電波がないときも前回開いたときの内容を読めます。オンラインに戻ると、最新の内容を読み込みます。
      </p>

      <h2>パソコンとスマホで同じメモを使えますか？</h2>
      <p>使えます。同じ Google アカウントでログインすれば、どの端末でも同じ板が開きます。</p>

      <h2>Google アカウントがなくても使えますか？</h2>
      <p>使えません。ログインは Google アカウントだけに対応しています。</p>

      <h2>書いたメモを他の人に見られることはありますか？</h2>
      <p>
        メモを読めるのはログインした本人だけで、公開や共有の機能はありません。取得する情報とその扱いは
        <Link to="/privacy">プライバシーポリシー</Link>をご覧ください。
      </p>

      <h2>どれくらいの量を書けますか？</h2>
      <p>
        板全体で {BOARD_MAX_LENGTH.toLocaleString("ja-JP")} 文字、セクションは{" "}
        {BOARD_MAX_SECTIONS.toLocaleString("ja-JP")}{" "}
        個までです。古いセクションは自動で消えていくので、ふだんの使い方で上限に届くことはあまりありません。
      </p>

      <h2>やめるときはどうすればいいですか？</h2>
      <p>
        ユーザーメニューの「アカウント削除」で、アカウントと書いたメモをすべて削除できます。削除した内容は元に戻せません。
      </p>
    </DocPage>
  );
}
