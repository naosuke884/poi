import {
  BOARD_MAX_LENGTH,
  BOARD_MAX_SECTIONS,
  MEMO_TTL_DAYS,
  TAG_MAX_LENGTH,
  TAG_MAX_REGISTERED,
} from "@shared/constants";
import { SUB_PAGES } from "@shared/site";
import { createFileRoute, Link } from "@tanstack/react-router";

import { DocPage } from "../-components/DocPage";

// 使い方とよくある質問 (ログイン不要)。検索の入口にもなるよう、できることを画面の言葉で説明する (issue #152)。
// よくある質問は、質問の形の検索や AI 検索の回答に引用されやすいよう、質問を見出しにして答えを本文に書く。
// 答えは折りたたまない (読み込んだだけで本文が読めるように。issue #151)
export const Route = createFileRoute("/(docs)/docs/guide")({
  component: Guide,
});

function Guide() {
  return (
    <DocPage title={SUB_PAGES["/docs/guide"].name}>
      <p>
        poi は、書いたメモが {MEMO_TTL_DAYS}{" "}
        日で自動で消えるメモ帳です。消えるメモなので、片付けや整理を気にせず、思いついたことをそのまま書いておけます。このページでは、書き方とメモが消えるしくみ、便利な機能を説明し、最後によくある質問に答えます。
      </p>

      <h2>はじめる</h2>
      <p>
        ヘッダーの「Google でログインして始める」からログインすると、すぐに自分の板 (メモを書く場所)
        が開きます。アプリのインストールや、名前・パスワードの登録はいりません。
      </p>

      <h2>メモを書く</h2>
      <p>板はメモを書く場所で、メモは「セクション」というカードに分かれて縦に並びます。</p>
      <ul>
        <li>
          「セクションを追加」(スマホでは右下の + ボタン)
          を押すと新しいセクションができ、そのまま書き始められます。空行をいくつ続けても、同じセクションのままです。
        </li>
        <li>
          書いた内容は自動で保存されます。保存できたかどうかは、ヘッダーのアイコンで分かります。
        </li>
        <li>
          書いたセクションは押すと (キーボードでは Enter で) 書き直せます。書き終わったら Esc
          キーか、セクションの外を押すと表示に戻ります。
        </li>
        <li>セクションの先頭で Backspace キーを押すと、前のセクションとつながります。</li>
      </ul>

      <h2>Markdown で書く</h2>
      <p>
        見出しと箇条書きは Markdown
        の記法で書けます。書いている間は記号のまま、書き終わると見出しや箇条書きとして表示されます。
      </p>
      <ul>
        <li>
          <code># 見出し</code> (<code>##</code> で小さい見出し)
        </li>
        <li>
          <code>- 箇条書き</code>、<code>1. 番号付きの箇条書き</code> (Tab キーで字下げ)
        </li>
        <li>URL はそのまま書けばリンクになります。</li>
      </ul>
      <p>
        太字・引用・チェックボックスなど、ほかの記法は使えません。書いた文字がそのまま表示されます。
      </p>
      <p>
        URL だけを書いたリンクは、リンク先のページの題名で表示されます (題名が取れないときは短くした
        URL のまま、編集中は URL のままです)。題名は poi
        のサーバーがリンク先のページから読み込みます。
      </p>

      <h2>ボタンで書式を付ける</h2>
      <p>
        書いているセクションの下に、書式のボタンが並びます。記号を打たなくても、押すだけで見出し
        (H1・H2)・箇条書き・番号付きリストを付け外しでき、インデントを下げたり戻したりできます。元に戻す・やり直すのボタンもあります。スマホで記号を打ちにくいときに便利です。
      </p>

      <h2>メモが消えるしくみ</h2>
      <ul>
        <li>
          メモはセクションごとに、最初に書いてから {MEMO_TTL_DAYS}{" "}
          日がたつと自動で消えます。あとから書き足しても、消える日は変わりません。
        </li>
        <li>
          各セクションの左上に「あと N 日」と残りの日数が出て、残り 1
          日になるとオレンジ色になります。
        </li>
        <li>
          消えたメモは元に戻せません。残しておきたい内容は、消える前にコピーして別の場所に保存してください。新しいセクションに書き直せば、そこからまた{" "}
          {MEMO_TTL_DAYS} 日のあいだ残ります。
        </li>
      </ul>

      <h2>タグを付けて、タグで絞り込む</h2>
      <p>
        セクションの右上にあるタグのボタンを押すと、タグを選ぶ小さな窓が開きます。登録してあるタグを押すと、そのセクションに付きます
        (1 つのセクションに 1
        つ)。タグには名前に合うアイコンが自動で付き、セクションにはそのアイコンで表示されます
        (名前は、パソコンではアイコンにポインタを乗せると出ます。スマホでは、アイコンを押して開く窓の上に出ます)。合うアイコンが見つからないタグには、決まったアイコンが付きます。
      </p>
      <p>
        窓の入力欄に打つとタグを絞り込めて、無い名前なら Enter (または一覧の + の行)
        で新しく登録して付けられます。タグは {TAG_MAX_REGISTERED} 個まで、名前は {TAG_MAX_LENGTH}{" "}
        文字まで登録できます。まだ何も書いていないセクションには、タグを付けられません。タグの登録・名前の変更・削除は、オンラインのときにできます。
      </p>
      <p>
        タグを外すには、窓の上のタグの × を押します (入力欄が空のときは Backspace
        キーでも外せます)。登録したタグは、付けたメモが消えた後も残ります。タグの右の「…」から、名前を変えたり
        (Enter
        で保存)、登録を削除したりできます。名前を変えると付けていたセクションのタグも新しい名前になり、削除すると付けていたセクションから外れます
        (メモの内容は消えません)。
      </p>
      <p>
        タグを登録すると、板の上に「すべて」「タグなし」と各タグのボタンが並びます
        (スクロールしても画面の上に残ります)。タグのボタンを押すと、そのタグを付けたセクションだけが表示されます。たとえば毎日のメモに「作業ログ」のタグを付けておくと、作業の記録だけを続けて読めます。絞り込んでいる間に足したセクションには、そのタグが付きます。
      </p>

      <h2>コピー・画像・削除</h2>
      <p>セクションの右上にあるボタンで、そのセクションを操作できます。</p>
      <ul>
        <li>コピー: 本文をテキストとしてコピーします。</li>
        <li>スクショ: 表示しているとおりの画像にします。チャットや SNS にそのまま貼れます。</li>
        <li>削除: セクションを消します。数秒のあいだは「元に戻す」で取り消せます。</li>
      </ul>

      <h2>スマホで使う</h2>
      <p>
        スマホのブラウザでもそのまま使えます。ユーザーメニューの「ホーム画面に追加」から、アプリのようにホーム画面に置いて全画面で開けます。電波がないときも、前回開いたときの内容は読めます。
      </p>
      <p>同じ Google アカウントでログインすれば、パソコンとスマホで同じ板を使えます。</p>

      <h2>アカウントを削除する</h2>
      <p>
        ユーザーメニューの「アカウント削除」で、アカウントと書いたメモをすべて削除できます。詳しくは
        <Link to="/terms">利用規約</Link>と<Link to="/privacy">プライバシーポリシー</Link>
        をご覧ください。
      </p>

      {/* 旧 /faq から来た人やリンクが、質問の先頭へ飛べるように id を付ける */}
      <h2 id="faq">よくある質問</h2>

      <h3>消えたメモは元に戻せますか？</h3>
      <p>
        戻せません。{MEMO_TTL_DAYS}{" "}
        日を過ぎて消えたメモは、運営者に頼んでも復元できません。残しておきたい内容は、消える前にコピーして別の場所に保存してください。自分で削除したセクションは、削除した直後の数秒のあいだだけ「元に戻す」で取り消せます。
      </p>

      <h3>メモはいつ消えますか？</h3>
      <p>
        セクションごとに、最初に書いてから {MEMO_TTL_DAYS}{" "}
        日がたつと自動で消えます。各セクションの左上に「あと N 日」と残りの日数が出て、残り 1
        日になるとオレンジ色になるので、消える前に気づけます。
      </p>

      <h3>書き足したり直したりすると、消える日は延びますか？</h3>
      <p>
        延びません。消える日は、そのセクションを最初に書いた日から数えます。続きを長く残したいときは、新しいセクションに書いてください。
      </p>

      <h3>消えるまでの日数は変えられますか？</h3>
      <p>
        変えられません。どのメモも、書いてから {MEMO_TTL_DAYS}{" "}
        日で消えます。早く消したいセクションは、自分で削除できます。
      </p>

      <h3>タグも {MEMO_TTL_DAYS} 日で消えますか？</h3>
      <p>
        セクションに付けたタグは、そのセクションと一緒に消えます。登録したタグそのものは消えずに残り、次のメモにも使えます。使わなくなったタグは、タグを選ぶ窓の「…」から削除できます。
      </p>

      <h3>無料ですか？</h3>
      <p>無料で使えます。有料のプランはありません。</p>

      <h3>スマホで使えますか？</h3>
      <p>
        使えます。スマホのブラウザでそのまま開けるほか、ユーザーメニューの「ホーム画面に追加」から、アプリのようにホーム画面に置いて全画面で開けます。App
        Store や Google Play からインストールするアプリはありません。
      </p>

      <h3>電波がないときも使えますか？</h3>
      <p>
        ホーム画面に追加しているか、一度開いたことがあれば、電波がないときも前回開いたときの内容を読めます。オンラインに戻ると、最新の内容を読み込みます。
      </p>

      <h3>パソコンとスマホで同じメモを使えますか？</h3>
      <p>使えます。同じ Google アカウントでログインすれば、どの端末でも同じ板が開きます。</p>

      <h3>Google アカウントがなくても使えますか？</h3>
      <p>使えません。ログインは Google アカウントだけに対応しています。</p>

      <h3>書いたメモを他の人に見られることはありますか？</h3>
      <p>
        公開や共有の機能はなく、書いたメモが他の利用者から見えることはありません。メモはサーバーに保存するため、運営者は技術的にはアクセスできますが、障害の調査、不正な利用への対応、法令に基づく場合を除き、内容を閲覧しません。なお、タグのアイコンを選ぶために、タグの名前を外部のサービスに送ります
        (送るのはタグの名前だけです)。また、リンクの題名を表示するために、poi
        のサーバーがリンク先のページを読み込みます (リンク先に送るのは URL
        だけです)。どちらも、利用者を特定する情報は送りません。取得する情報とその扱いは
        <Link to="/privacy">プライバシーポリシー</Link>をご覧ください。
      </p>

      <h3>どれくらいの量を書けますか？</h3>
      <p>
        板全体で {BOARD_MAX_LENGTH.toLocaleString("ja-JP")} 文字、セクションは{" "}
        {BOARD_MAX_SECTIONS.toLocaleString("ja-JP")}{" "}
        個までです。古いセクションは自動で消えていくので、ふだんの使い方で上限に届くことはあまりありません。タグは{" "}
        {TAG_MAX_REGISTERED} 個まで登録できます。
      </p>

      <h3>やめるときはどうすればいいですか？</h3>
      <p>
        ユーザーメニューの「アカウント削除」で、アカウントと書いたメモをすべて削除できます。削除した内容は元に戻せません。
      </p>
    </DocPage>
  );
}
